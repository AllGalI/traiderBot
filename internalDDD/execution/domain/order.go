package domain

import (
	"time"

	marketDomain "traiderBot/internalDDD/market/domain"

	"github.com/shopspring/decimal"
)

type OrderStatus uint8

const (
	OrderPending OrderStatus = iota
	OrderSubmitted
	OrderPartiallyFilled
	OrderFilled
	OrderCancelled
	OrderFailed
)

func (s OrderStatus) String() string {
	switch s {
	case OrderPending:
		return "pending"

	case OrderSubmitted:
		return "submitted"

	case OrderPartiallyFilled:
		return "partially_filled"

	case OrderFilled:
		return "filled"

	case OrderCancelled:
		return "cancelled"

	case OrderFailed:
		return "failed"

	default:
		return "unknown"
	}
}

type Order struct {
	StepIndex int

	Symbol    string
	Direction marketDomain.TradeDirection

	// ClientOrderID is the identifier generated by our system.
	// It allows us to find/reconcile an order on the exchange
	// if the execution request times out or otherwise fails.
	ClientOrderID string

	// ExchangeOrderID is the identifier assigned by the exchange.
	// It may be empty until the exchange accepts the order.
	ExchangeOrderID string

	RequestedAmount   decimal.Decimal
	ExpectedAmountOut decimal.Decimal
	ExecutedAmount    decimal.Decimal
	ReceivedAmount    decimal.Decimal

	Status OrderStatus

	CreatedAt   time.Time
	SubmittedAt time.Time
	FilledAt    time.Time
}

func NewOrder(
	stepIndex int,
	result OrderExecutionResult,
) Order {
	return Order{
		StepIndex: stepIndex,

		Symbol:    result.Symbol,
		Direction: result.Direction,

		ClientOrderID:   result.ClientOrderID,
		ExchangeOrderID: result.ExchangeOrderID,

		RequestedAmount:   result.RequestedAmount,
		ExpectedAmountOut: result.ExpectedAmountOut,
		ExecutedAmount:    result.ExecutedAmount,
		ReceivedAmount:    result.ReceivedAmount,

		Status: result.Status,

		CreatedAt:   result.CreatedAt,
		SubmittedAt: result.SubmittedAt,
		FilledAt:    result.FilledAt,
	}
}
// =====================================================================
// Рекомендованный стартовый конфиг
// =====================================================================
//
// Обоснование по каждому полю — исходя из вашего дампа статистики
// (39 символов, generated_at 2026-08-11):
//
//   WindowSize=400, RecalcEvery=20
//     Компромисс между памятью и скоростью адаптации. Для быстрых пар
//     (BTCUSDT, ~45000 апдейтов за период сбора) окно в 400 заполняется
//     за секунды. Для медленных (ETCBTC, медиана интервала 13с) окно
//     заполнится примерно за час — это нормально: до полного заполнения
//     percentile() просто считается по тому, что накопилось, а холодный
//     старт закрывает SeedFromHistory.
//
//   MinFloor=200ms
//     Нижний пол порога. У самых быстрых пар в дампе (BTCUSDT p99=175мс,
//     ETHUSDT p99=183мс, USDCUSDT p99=188мс) k*p99 при PercentileK=2.5
//     и так даёт 440-470мс, то есть пол не бьёт по ним. Он нужен как
//     страховка на случай аномально маленького p99 (например, в первые
//     секунды жизни процесса, если буфер почти пуст, а посева не было).
//
//   PercentileK=2.5
//     Средний по палате множитель. Часть пар в дампе (BNBUSDT, TRXUSDT,
//     TRXBTC, ZECBTC) имеют p999 в 5-20 раз выше p99 — это значит, у них
//     бывают редкие, но регулярные "замирания" на десятки секунд, которые
//     подряд обычным k=2 будут постоянно ложно триггерить staleness.
//     Полностью покрыть такой хвост (k~20) нельзя — иначе для быстрых пар
//     реальная поломка фида будет обнаруживаться слишком поздно. 2.5 —
//     стартовая точка для бэктеста, а не окончательное значение; для пар
//     с особо тяжёлым хвостом (BNBUSDT/TRXUSDT/TRXBTC/ZECBTC) имеет смысл
//     считать per-symbol override, если такое решите добавить в конфиг.
//
//   MaxHeartbeatGap=10s
//     ВАЖНО: этот дамп содержит интервалы между апдейтами СТАКАНА, а не
//     интервалы heartbeat/ping соединения — это разные каналы данных, и
//     из этой статистики MaxHeartbeatGap не выводится. 10s — общий
//     ориентир (2-3x от типичного пинга большинства бирж), но подставьте
//     реальный период heartbeat вашего конкретного фида.
//
//   MinSamples=50
//     Как и обсуждали; при использовании SeedFromHistory порог
//     фактически применяется сразу, а не после набора реальных 50 апдейтов.
//
//   DefaultThreshold=3s
//     Это ТОЛЬКО fallback на случай, если для символа не был вызван
//     SeedFromHistory (например, новый листинг, которого нет в дампе).
//     3с — компромисс более безопасный, чем 300мс (не будет постоянно
//     резать медленные пары), но всё ещё оставляет разумную защиту для
//     быстрых пар. Если для каждого символа делаете сид при старте —
//     это значение почти никогда не будет использовано в проде.
//
//   MaxZSpread=2.0
//     Стартовое значение для кросс-ногового сравнения, требует бэктеста.
//
// DefaultConfig возвращает стартовый конфиг с этими значениями.
func DefaultConfig() FreshnessConfig {
	return FreshnessConfig{
		WindowSize:  400,
		RecalcEvery: 20,

		MinFloor:    200 * time.Millisecond,
		PercentileK: 2.5,

		MaxHeartbeatGap: 10 * time.Second,

		MinSamples:       50,
		DefaultThreshold: 3 * time.Second,

		EnableSeqGapCheck: true,
		SeqIncrement:      1,

		MaxZSpread: 2.0,
	}
}

// =====================================================================
// Загрузка дампа статистики и посев трекера
// =====================================================================

// statsDump — структура, соответствующая формату вашего JSON-дампа
// ({"generated_at": ..., "symbols": {"ADABTC": {...}, ...}}).
// Незнакомые/лишние поля (distribution, mean_ms и т.п.) json.Unmarshal
// просто проигнорирует — они не нужны для посева.
type statsDump struct {
	GeneratedAt string                `json:"generated_at"`
	Symbols     map[string]symbolStat `json:"symbols"`
}

type symbolStat struct {
	Count int     `json:"count"`
	P95Ms float64 `json:"p95_ms"`
	P99Ms float64 `json:"p99_ms"`
}

// SeedTrackerFromFile читает JSON-дамп статистики (в формате, который вы
// прислали) и сеет им trackr через SeedFromHistory для каждого символа.
// Возвращает число заполненных символов.
//
// Вызывать один раз при старте процесса, после NewFreshnessTracker и до
// того, как пойдут первые реальные RecordUpdate/RecordHeartbeat (хотя это
// и не обязательно строго — SeedFromHistory можно звать и на уже
// работающий трекер, если, скажем, догружаете статистику по новому символу
// на лету).
func SeedTrackerFromFile(tracker *FreshnessTracker, path string) (int, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return 0, fmt.Errorf("не удалось прочитать файл статистики: %w", err)
	}

	var dump statsDump
	if err := json.Unmarshal(raw, &dump); err != nil {
		return 0, fmt.Errorf("не удалось распарсить дамп статистики: %w", err)
	}

	count := 0
	for symbol, stat := range dump.Symbols {
		if stat.P99Ms <= 0 {
			// Пропускаем символы без осмысленной статистики (например,
			// слишком мало сэмплов за период сбора), чтобы не засеять
			// трекер нулевым/некорректным порогом.
			continue
		}
		tracker.SeedFromHistory(symbol, stat.P95Ms, stat.P99Ms, stat.Count)
		count++
	}
	return count, nil
}